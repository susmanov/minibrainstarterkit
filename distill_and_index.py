def iter_source_files(root: str):
    """Yield (rel_to_source, full_abs_path, ext) for every source doc in Source/."""
    source_abs = os.path.join(root, SOURCE_DIR)
    if not os.path.isdir(source_abs):
        return
    exclude = {".claude", "_archive"}
    for dirpath, dirnames, filenames in os.walk(source_abs):
        dirnames[:] = [d for d in dirnames if d not in exclude and not d.startswith(".")]
        for fn in filenames:
            if fn.startswith("~$") or fn.endswith(".tmp") or fn.lower() == "desktop.ini":
                continue
            ext = os.path.splitext(fn)[1].lower()
            if ext not in SOURCE_EXTS and ext != OPTIONAL_VSDX_EXT:
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, source_abs).replace(os.sep, "/")
            yield rel, full, ext


def is_locked(full_path: str) -> bool:
    d, fn = os.path.split(full_path)
    return safe_exists(os.path.join(d, "~$" + fn))


# ---------------------------------------------------------------------------
# Main extraction pass
# ---------------------------------------------------------------------------

def process_file(root: str, rel: str, full: str, ext: str, force: bool, dry_run: bool, log: dict) -> str:
    """Returns: 'new' | 'merged-in-place' | 'merged-appended' | 'current' |
                'locked' | 'protected' | 'unsupported' | 'error'."""
    twin_rel = rel + ".md"
    twin_abs = os.path.join(root, TWINS_DIR, twin_rel)

    if is_locked(full):
        log["locked"].append(rel)
        return "locked"

    try:
        mtime = safe_mtime_utc(full)
    except OSError as e:
        log["errors"].append((rel, "mtime: %s" % e))
        return "error"

    twin_exists = safe_exists(twin_abs)
    existing_text = None
    if twin_exists:
        stamp_str, is_auto = read_twin_meta(twin_abs)
        stamp_dt = parse_iso(stamp_str)
        is_stale = stamp_dt is None or mtime > stamp_dt + datetime.timedelta(seconds=2)
        if not is_stale:
            return "current"
        if not is_auto and not force:
            log["protected"].append(rel)
            return "protected"
        try:
            existing_text = safe_read_text(twin_abs)
        except OSError as e:
            log["errors"].append((rel, "read twin: %s" % e))
            return "error"

    if ext == OPTIONAL_VSDX_EXT:
        try:
            raw = safe_read_bytes(full)
            body, extra = extract_vsdx(raw)
        except Exception as e:
            log["errors"].append((rel, "extract: %s" % e))
            return "error"
    elif ext in EXTRACTORS:
        try:
            raw = safe_read_bytes(full)
            body, extra = EXTRACTORS[ext](raw)
        except Exception as e:
            log["errors"].append((rel, "extract: %s" % e))
            return "error"
    else:
        log["unsupported"].append(rel)
        return "unsupported"

    mtime_iso = mtime.strftime("%Y-%m-%dT%H:%M:%SZ")
    today = datetime.date.today().isoformat()
    summary = mechanical_summary(ext, extra)
    tags = derive_tags(body)
    new_text, mode = merge_twin(existing_text, rel, mtime_iso, today, body, summary, tags)

    if not dry_run:
        safe_write_text(twin_abs, new_text)

    return "new" if mode == "new" else ("merged-in-place" if mode == "in-place" else "merged-appended")


# ---------------------------------------------------------------------------
# Orphan sweep
# ---------------------------------------------------------------------------

def sweep_orphans(root: str, all_source_rels: set[str], dry_run: bool, log: dict) -> None:
    twins_abs = os.path.join(root, TWINS_DIR)
    archive_abs = os.path.join(twins_abs, "_archive")
    if not os.path.isdir(twins_abs):
        return
    for dirpath, dirnames, filenames in os.walk(twins_abs):
        rel_dir = os.path.relpath(dirpath, twins_abs).replace(os.sep, "/")
        if rel_dir == "_archive" or rel_dir.startswith("_archive/"):
            dirnames[:] = []
            continue
        dirnames[:] = [d for d in dirnames if d != "_archive"]
        for fn in filenames:
            if not fn.endswith(".md"):
                continue
            twin_abs = os.path.join(dirpath, fn)
            twin_rel = os.path.relpath(twin_abs, twins_abs).replace(os.sep, "/")
            source_rel = twin_rel[:-3]  # strip ".md"
            if source_rel in all_source_rels:
                continue
            dest = os.path.join(archive_abs, twin_rel)
            if not dry_run:
                safe_move(twin_abs, dest)
            log["orphans"].append(source_rel)


# ---------------------------------------------------------------------------
# index.md generation — scan all twins and rebuild the table from scratch
# ---------------------------------------------------------------------------

def _escape_cell(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ").strip()


def write_index_md(root: str, dry_run: bool, log: dict) -> None:
    """Scan all (non-archived) twins and regenerate Memory/index.md."""
    twins_abs = os.path.join(root, TWINS_DIR)
    orphan_set = set(log["orphans"])
    rows: list[tuple] = []

    if os.path.isdir(twins_abs):
        for dirpath, dirnames, filenames in os.walk(twins_abs):
            rel_dir = os.path.relpath(dirpath, twins_abs).replace(os.sep, "/")
            if rel_dir == "_archive" or rel_dir.startswith("_archive/"):
                dirnames[:] = []
                continue
            dirnames[:] = [d for d in dirnames if d != "_archive"]
            for fn in filenames:
                if not fn.endswith(".md"):
                    continue
                twin_abs = os.path.join(dirpath, fn)
                twin_rel = os.path.relpath(twin_abs, twins_abs).replace(os.sep, "/")
                source_rel = twin_rel[:-3]  # strip ".md"

                if source_rel in orphan_set:
                    continue

                fm = read_twin_frontmatter(twin_abs)
                file_name = os.path.basename(source_rel)
                summary = fm.get("summary", "")
                tags = fm.get("tags", "")
                modified = fm.get("source_modified", "")
                if modified and "T" in modified:
                    modified = modified.split("T")[0]

                source_path = SOURCE_DIR + "/" + source_rel
                twin_path = TWINS_DIR + "/" + twin_rel
                rows.append((source_rel, file_name, source_path, twin_path, summary, tags, modified))

    rows.sort(key=lambda r: r[0].lower())

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Project Brain — Index",
        "",
        "_Last updated: %s · %d file(s)_" % (now, len(rows)),
        "",
        "To find files: grep this table for a topic, then open the twin at the path in the Twin column.",
        "",
        "| File | Source path | Twin | Summary | Tags | Modified |",
        "|---|---|---|---|---|---|",
    ]
    for _, file_name, source_path, twin_path, summary, tags, modified in rows:
        lines.append("| %s | %s | %s | %s | %s | %s |" % (
            _escape_cell(file_name),
            _escape_cell(source_path),
            _escape_cell(twin_path),
            _escape_cell(summary),
            _escape_cell(tags),
            _escape_cell(modified),
        ))

    index_text = "\n".join(lines) + "\n"
    if not dry_run:
        safe_write_text(os.path.join(root, INDEX_PATH), index_text)

    log["index_total"] = len(rows)


