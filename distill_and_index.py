# Entry point
# ---------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument(
        "--root", default=".",
        help="Project root — the folder containing Source/ and Memory/ (default: current directory)",
    )
    ap.add_argument(
        "--force", action="store_true",
        help="Also refresh hand-crafted twins that have no AUTO-EXTRACT block yet "
             "(the fresh extract is appended; existing content is never removed)",
    )
    ap.add_argument("--dry-run", action="store_true", help="Preview actions, write nothing")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    source_abs = os.path.join(root, SOURCE_DIR)
    if not os.path.isdir(source_abs):
        print(
            'WARNING: "%s" not found under %s — create it and add your source files first.' % (SOURCE_DIR, root),
            file=sys.stderr,
        )

    log: dict = {
        "locked": [], "protected": [], "unsupported": [], "errors": [], "orphans": [],
        "new_files": [], "merged_in_place_files": [], "merged_appended_files": [],
    }
    counts = {"new": 0, "merged-in-place": 0, "merged-appended": 0, "current": 0}
    all_source_rels: set[str] = set()

    for rel, full, ext in iter_source_files(root):
        all_source_rels.add(rel)
        result = process_file(root, rel, full, ext, args.force, args.dry_run, log)
        if result in counts:
            counts[result] += 1
        if result == "new":
            log["new_files"].append(rel)
        elif result == "merged-in-place":
            log["merged_in_place_files"].append(rel)
        elif result == "merged-appended":
            log["merged_appended_files"].append(rel)

    sweep_orphans(root, all_source_rels, args.dry_run, log)
    write_index_md(root, args.dry_run, log)
    write_report(root, counts, log, args.dry_run)


if __name__ == "__main__":
    main()
