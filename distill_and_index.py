#!/usr/bin/env python3
"""
distill_and_index.py — Brain Lite
===================================

Zero-LLM refresh of the Claude/Memory/twins/*.md twins and Claude/Memory/index.md
for a project brain. Run it from the project root (the folder containing
"Project Documents/" and "Claude/"):

    distill_and_index.exe            # do the work
    distill_and_index.exe --dry-run  # preview only, writes nothing
    distill_and_index.exe --force    # also refresh hand-crafted twins

What it does
-------------
1. Walks "Project Documents/" for source documents (.pptx .docx .xlsx .pdf, plus
   best-effort .vsdx if the optional `vsdx` package is installed). Skips Claude/,
   .claude/, hidden files, ~$ lock files, and *.tmp.
2. For each source file, compares its mtime against the twin's
   `source_modified:` frontmatter stamp (Claude/Memory/twins/<relpath>.md):
     - no twin yet             -> NEW, extract and create it
     - source newer than stamp -> STALE, re-extract and merge it
     - stamp is current        -> untouched
3. Extraction is FAITHFUL, NOT ANALYTICAL: slide-by-slide text + speaker
   notes for pptx, sheet dumps for xlsx, page text for pdf, paragraph/table
   text for docx. Raw text only — no synthesised narrative, no LLM.
4. Twin merge preserves human edits:
     - Extracted text lives inside <!-- AUTO-EXTRACT:BEGIN --> /
       <!-- AUTO-EXTRACT:END --> markers. Only that region is ever replaced.
     - Frontmatter fields added by humans (reuse_notes, etc.) are never touched.
     - A twin with no AUTO-EXTRACT block requires --force before it's touched;
       the fresh extract is appended, nothing existing is removed.
5. After the extraction pass, Memory/index.md is fully regenerated by scanning
   all twins in Memory/twins/ and reading their frontmatter. The index is
   always reproducible from the twins alone — no separate state file.
6. Orphaned twins (source file deleted) are moved to Memory/twins/_archive/
   and dropped from the index.
7. Writes a run report to Memory/.last-distill-report.txt.

Requirements
------------
    pip install python-pptx python-docx openpyxl pypdf
    pip install vsdx   # optional, only needed for .vsdx files
"""

import argparse
import datetime
import io
import os
import re
import sys

# ---------------------------------------------------------------------------
# Config — edit these for your project
# ---------------------------------------------------------------------------

SOURCE_DIR = "Project Documents"      # folder containing all source documents
TWINS_DIR  = "Claude/Memory/twins"   # output folder for markdown twins
INDEX_PATH = "Claude/Memory/index.md" # the searchable index

SOURCE_EXTS = {".pptx", ".docx", ".xlsx", ".pdf"}
OPTIONAL_VSDX_EXT = ".vsdx"
MAX_ROWS_PER_SHEET = 500

# Keyword → tag mapping for auto-tagging. Add terms relevant to your project.
# Example: "integration": "integration", "governance": "governance"
KEYWORD_TAGS: dict[str, str] = {}

AUTO_MARK_BEGIN = (
    "<!-- AUTO-EXTRACT:BEGIN (maintained by distill_and_index.py -- content "
    "below is regenerated from source on every run; do not hand-edit inside "
    "this block, edits will be lost on the next refresh) -->"
)
AUTO_MARK_END = "<!-- AUTO-EXTRACT:END -->"
AUTO_BLOCK_RE = re.compile(re.escape(AUTO_MARK_BEGIN) + r".*?" + re.escape(AUTO_MARK_END), re.DOTALL)
FRONTMATTER_RE = re.compile(r"^---[ \t]*\r?\n(.*?)\n---[ \t]*\r?\n", re.DOTALL)


# ---------------------------------------------------------------------------
# Long-path-safe file I/O (Windows MAX_PATH workaround)
# ---------------------------------------------------------------------------

def _win_prefixed(path: str) -> str:
    ap = os.path.abspath(path)
    if os.name == "nt" and not ap.startswith("\\\\?\\"):
        ap = "\\\\?\\" + ap
    return ap


def safe_read_bytes(path: str) -> bytes:
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError:
        with open(_win_prefixed(path), "rb") as f:
            return f.read()


def safe_write_text(path: str, text: str) -> None:
    d = os.path.dirname(path)
    if d:
        try:
            os.makedirs(d, exist_ok=True)
        except OSError:
            os.makedirs(_win_prefixed(d), exist_ok=True)
    try:
        with io.open(path, "w", encoding="utf-8") as f:
            f.write(text)
    except OSError:
        with io.open(_win_prefixed(path), "w", encoding="utf-8") as f:
            f.write(text)


def safe_read_text(path: str) -> str:
    try:
        with io.open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        with io.open(_win_prefixed(path), encoding="utf-8") as f:
            return f.read()


def safe_mtime_utc(path: str) -> datetime.datetime:
    try:
        ts = os.path.getmtime(path)
    except OSError:
        ts = os.path.getmtime(_win_prefixed(path))
    return datetime.datetime.fromtimestamp(ts, tz=datetime.timezone.utc)


def safe_exists(path: str) -> bool:
    if os.path.exists(path):
        return True
    try:
        return os.path.exists(_win_prefixed(path))
    except OSError:
        return False


def safe_move(src: str, dst: str) -> None:
    d = os.path.dirname(dst)
    if d:
        try:
            os.makedirs(d, exist_ok=True)
        except OSError:
            os.makedirs(_win_prefixed(d), exist_ok=True)
    data = safe_read_bytes(src)
    safe_write_text(dst, data.decode("utf-8", errors="replace"))
    try:
        os.remove(src)
    except OSError:
        os.remove(_win_prefixed(src))


