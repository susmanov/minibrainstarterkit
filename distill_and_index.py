def extract_pptx(raw_bytes: bytes):
    from pptx import Presentation
    prs = Presentation(io.BytesIO(raw_bytes))
    lines = []
    titles = []
    for i, slide in enumerate(prs.slides, 1):
        lines.append("=== SLIDE %d ===" % i)
        title_shape = None
        try:
            title_shape = slide.shapes.title
        except Exception:
            pass
        if title_shape is not None and getattr(title_shape, "has_text_frame", False):
            t = title_shape.text_frame.text.strip()
            if t:
                lines.append("[TITLE] " + t)
                titles.append(t)
        for shape in slide.shapes:
            if shape is title_shape:
                continue
            if getattr(shape, "has_text_frame", False):
                txt = shape.text_frame.text
                if txt and txt.strip():
                    lines.append(txt)
            if getattr(shape, "has_table", False):
                for row in shape.table.rows:
                    lines.append(" | ".join(c.text for c in row.cells))
        try:
            if slide.has_notes_slide and slide.notes_slide.notes_text_frame is not None:
                nt = slide.notes_slide.notes_text_frame.text
                if nt and nt.strip():
                    lines.append("[SPEAKER NOTES] " + nt)
        except Exception:
            pass
        lines.append("")
    header = "**Slide count:** %d\n" % len(prs.slides)
    return header + "\n".join(lines), titles


def extract_xlsx(raw_bytes: bytes):
    from openpyxl import load_workbook
    wb = load_workbook(io.BytesIO(raw_bytes), data_only=True, read_only=True)
    lines = []
    sheet_summaries = []
    for sheet in wb.sheetnames:
        ws = wb[sheet]
        try:
            maxr = ws.max_row or 0
            maxc = ws.max_column or 0
        except Exception:
            maxr = maxc = 0
        sheet_summaries.append("%s (%sx%s)" % (sheet, maxr, maxc))
        lines.append("=== SHEET: %s (rows=%s cols=%s) ===" % (sheet, maxr, maxc))
        count = 0
        for row in ws.iter_rows(values_only=True):
            if row is None:
                continue
            vals = [str(v) for v in row if v is not None]
            if vals:
                lines.append(" | ".join(vals))
                count += 1
            if count >= MAX_ROWS_PER_SHEET:
                lines.append("...(truncated at %d non-empty rows)..." % MAX_ROWS_PER_SHEET)
                break
        lines.append("")
    header = "**Sheets:** " + ", ".join(sheet_summaries) + "\n"
    return header + "\n".join(lines), sheet_summaries


def extract_pdf(raw_bytes: bytes):
    try:
        from pypdf import PdfReader
    except ImportError:
        from PyPDF2 import PdfReader  # type: ignore[no-redef]
    reader = PdfReader(io.BytesIO(raw_bytes))
    lines = []
    empty_pages = 0
    for i, page in enumerate(reader.pages, 1):
        lines.append("=== PAGE %d ===" % i)
        try:
            txt = page.extract_text() or ""
        except Exception:
            txt = ""
        if not txt.strip():
            empty_pages += 1
            lines.append("[no extractable text via pypdf on this page]")
        else:
            lines.append(txt)
        lines.append("")
    n = len(reader.pages)
    header = "**Page count:** %d" % n
    if empty_pages:
        header += "  (**%d page(s) had no extractable text**)" % empty_pages
    header += "\n"
    return header + "\n".join(lines), n


def extract_docx(raw_bytes: bytes):
    from docx import Document
    doc = Document(io.BytesIO(raw_bytes))
    lines = []
    for p in doc.paragraphs:
        if p.text.strip():
            style = (p.style.name if p.style is not None else "") or ""
            if style.lower().startswith("heading"):
                lines.append("### " + p.text)
            else:
                lines.append(p.text)
    for ti, table in enumerate(doc.tables, 1):
        lines.append("\n=== TABLE %d ===" % ti)
        for row in table.rows:
            lines.append(" | ".join(c.text for c in row.cells))
    header = "**Paragraph count:** %d, **Table count:** %d\n" % (len(doc.paragraphs), len(doc.tables))
    return header + "\n".join(lines), len(doc.paragraphs)


def extract_vsdx(raw_bytes: bytes):
    try:
        import vsdx
    except ImportError:
        raise RuntimeError("vsdx package not installed — run `pip install vsdx`")
    import tempfile
    with tempfile.NamedTemporaryFile(suffix=".vsdx", delete=False) as tf:
        tf.write(raw_bytes)
        tmp_path = tf.name
    try:
        vf = vsdx.VisioFile(tmp_path)
        lines = []
        for pi, page in enumerate(vf.pages, 1):
            lines.append("=== PAGE %d: %s ===" % (pi, getattr(page, "name", "")))
            for shape in page.child_shapes:
                text = getattr(shape, "text", "")
                if text and text.strip():
                    lines.append(text.strip())
        header = "**Page count:** %d\n" % len(vf.pages)
        return header + "\n".join(lines), len(vf.pages)
    finally:
        try:
            os.remove(tmp_path)
        except OSError:
            pass


EXTRACTORS = {
    ".pptx": extract_pptx,
    ".xlsx": extract_xlsx,
    ".pdf":  extract_pdf,
    ".docx": extract_docx,
}


# ---------------------------------------------------------------------------
# Mechanical summary + tag derivation
# ---------------------------------------------------------------------------

def derive_tags(text: str) -> list[str]:
    lower = text.lower()
    seen: set[str] = set()
    out: list[str] = []
    for kw, tag in KEYWORD_TAGS.items():
        if kw in lower and tag not in seen:
            seen.add(tag)
            out.append(tag)
    return out[:8]


def mechanical_summary(ext: str, extra) -> str:
    if ext == ".pptx":
        titles = extra[:6]
        s = "PowerPoint deck."
        if titles:
            s += " Slide titles: " + "; ".join(titles)
        return s
    if ext == ".xlsx":
        return "Excel workbook. Sheets: " + ", ".join(str(x) for x in extra[:10])
    if ext == ".pdf":
        return "PDF, %d page(s)." % extra
    if ext == ".docx":
        return "Word document, %d paragraph(s)." % extra
    return "Document."


# ---------------------------------------------------------------------------
# Twin frontmatter helpers
# ---------------------------------------------------------------------------

def read_twin_meta(twin_path: str) -> tuple[str | None, bool]:
    """Return (source_modified_str_or_None, is_script_generated)."""
    try:
        text = safe_read_text(twin_path)
    except OSError:
        return None, False
    m = FRONTMATTER_RE.match(text)
    if not m:
        return None, False
    fm = m.group(1)
    sm = re.search(r"^source_modified:\s*(.+)$", fm, re.MULTILINE)
    gen = re.search(r"^generator:\s*auto-distill-script\s*$", fm, re.MULTILINE)
    return (sm.group(1).strip() if sm else None), bool(gen)


def read_twin_frontmatter(twin_path: str) -> dict[str, str]:
    """Return a dict of frontmatter key→value strings, or {}."""
    try:
        text = safe_read_text(twin_path)
    except OSError:
        return {}
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}
    result: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            result[k.strip()] = v.strip()
    return result


def parse_iso(s: str | None) -> datetime.datetime | None:
    if not s:
        return None
    s = s.strip().strip('"').strip("'")
    if s.lower() == "unknown":
        return None
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    try:
        dt = datetime.datetime.fromisoformat(s)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=datetime.timezone.utc)
    return dt


def _set_frontmatter_field(fm_text: str, key: str, value: str) -> str:
    """Replace an existing `key: value` line, or append one if absent.
    All other lines — including any human-added fields — are left untouched."""
    pattern = re.compile(r"^%s:.*$" % re.escape(key), re.MULTILINE)
    replacement = "%s: %s" % (key, value)
    if pattern.search(fm_text):
        return pattern.sub(lambda _: replacement, fm_text, count=1)
    return fm_text.rstrip("\n") + "\n" + replacement


def build_auto_block(body: str) -> str:
    return AUTO_MARK_BEGIN + "\n\n" + body.strip("\n") + "\n\n" + AUTO_MARK_END


def merge_twin(
    existing_text: str | None,
    source_rel: str,
    mtime_iso: str,
    today: str,
    body: str,
    summary: str,
    tags: list[str],
) -> tuple[str, str]:
    """
    Merge extracted body into a twin, preserving human-contributed frontmatter.
    Returns (new_text, mode) where mode is 'new', 'in-place', or 'appended'.
    """
    new_block = build_auto_block(body)
    tags_str = ", ".join(tags)
    # Guard against newlines / pipes breaking frontmatter / index table
    summary_safe = summary.replace("\n", " ").replace("|", "/")

    if existing_text is None:
        fm = (
            "source: {source}\n"
            "distilled: {distilled}\n"
            "source_modified: {mtime}\n"
            "generator: auto-distill-script\n"
            "summary: {summary}\n"
            "tags: {tags}"
        ).format(source=source_rel, distilled=today, mtime=mtime_iso,
                 summary=summary_safe, tags=tags_str)
        return "---\n%s\n---\n\n%s\n" % (fm, new_block), "new"

    m = FRONTMATTER_RE.match(existing_text)
    if m:
        fm, rest = m.group(1), existing_text[m.end():]
    else:
        fm, rest = "source: %s" % source_rel, existing_text

    fm = _set_frontmatter_field(fm, "distilled", today)
    fm = _set_frontmatter_field(fm, "source_modified", mtime_iso)
    fm = _set_frontmatter_field(fm, "summary", summary_safe)
    fm = _set_frontmatter_field(fm, "tags", tags_str)

    if AUTO_BLOCK_RE.search(rest):
        rest = AUTO_BLOCK_RE.sub(lambda _: new_block, rest, count=1)
        mode = "in-place"
    else:
        rest = rest.rstrip("\n") + "\n\n" + new_block + "\n"
        mode = "appended"

    return "---\n%s\n---\n%s" % (fm, rest), mode


